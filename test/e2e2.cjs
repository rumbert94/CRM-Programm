const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, acceptDownloads: true, locale: 'de-DE' });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  p.on('dialog', (d) => d.accept());
  await p.goto('http://localhost:4173/');
  await p.click('text=Firma anlegen');
  const fill = async (n, v) => p.fill(`[name="${n}"]`, v);
  await fill('name', 'Muster Gebäudetechnik'); await fill('owner', 'Max Muster'); await fill('street', 'Werkweg 3');
  await fill('zip', '16515'); await fill('city', 'Oranienburg'); await fill('phone', '0176 0000000'); await fill('email', 'info@example.de');
  await fill('vatId', 'DE123456789'); await fill('iban', 'DE02120300000000202051'); await fill('bic', 'BYLADEM1001'); await fill('bankName', 'Deutsche Kreditbank DKB');
  await fill('footerExtra', 'Meisterbetrieb'); await fill('customerPrefix', '');
  await fill('numbering.rechnung.start', '9');
  await p.click('button:has-text("Speichern")');
  await p.waitForURL(/einstellungen/);
  await p.click('.list a');
  await p.setInputFiles('#logoFile', 'test/out/logo.png');
  await p.waitForSelector('#logoRemove');
  const hint = await p.textContent('text=nächste Rechnung');
  await p.screenshot({ path: 'test/shots/b1-firma.png', fullPage: true });
  // Kunde
  await p.click('nav >> text=Kunden'); await p.click('text=+ Neuer Kunde');
  await fill('name', 'Firma Fred Muster'); await fill('street', 'Olafstraße 17'); await fill('zip', '13467'); await fill('city', 'Berlin');
  await p.click('form#f button:has-text("Speichern")'); await p.waitForSelector('#nf');
  await p.click('text=+ Angebot');
  await p.fill('[name=subject]', 'Friedrichsthaler Weg 10, 13467 Berlin\nBadsanierung');
  await p.click('#addTitle'); await p.locator('#items .item').last().locator('[data-k=title]').fill('Abbrucharbeiten');
  await p.click('#addItem');
  let it = p.locator('#items .item').last();
  await it.locator('[data-k=desc]').fill('Wand- und Bodenfliesen inkl. Kleber entfernen'); await it.locator('[data-k=qty]').fill('18,5'); await it.locator('[data-k=unit]').selectOption('MTK'); await it.locator('[data-k=price]').fill('24');
  await it.locator('[data-tpl]').click();
  await p.click('#addTitle'); await p.locator('#items .item').last().locator('[data-k=title]').fill('Sanitär');
  await p.click('#fromTpl');
  await p.fill('#tplQ', 'kleber');
  await p.screenshot({ path: 'test/shots/b2-vorlage.png' });
  await p.click('#tplList [data-id]');
  await p.waitForTimeout(1000);
  await p.screenshot({ path: 'test/shots/b3-angebot.png', fullPage: true });
  await p.click('#toRechnung'); await p.waitForSelector('#finalize');
  await p.selectOption('#serviceMode', 'period');
  await fill('serviceFrom', '2026-11-01'); await fill('serviceTo', '2026-11-14');
  await p.waitForTimeout(1000);
  await p.click('#finalize'); await p.waitForSelector('#zugferd');
  const h1 = await p.textContent('h1');
  await p.screenshot({ path: 'test/shots/b4-rechnung.png', fullPage: true });
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#zugferd')]);
  const fname = dl.suggestedFilename();
  await dl.saveAs('test/out/b-zugferd.pdf');
  await p.click('nav >> text=Vorlagen');
  await p.screenshot({ path: 'test/shots/b5-vorlagen.png' });
  console.log({ hint, h1, fname, errors });
  await b.close();
})();

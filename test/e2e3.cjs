const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, locale: 'de-DE', colorScheme: 'light' });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  p.on('dialog', (d) => d.accept());
  await p.goto('http://localhost:4173/');
  await p.click('text=Firma anlegen');
  const fill = async (n, v) => p.fill(`[name="${n}"]`, v);
  await fill('name', 'Test GmbH'); await fill('street', 'Weg 1'); await fill('zip', '12345'); await fill('city', 'Ort');
  await p.locator('[name="textsOn.angebotIntro"]').evaluate((e) => e.click());
  await p.locator('[data-textfield]').first().screenshot({ path: 'test/shots/c1-switch.png' });
  await p.click('button:has-text("Speichern")'); await p.waitForURL(/einstellungen/);
  await p.click('nav >> text=Kunden'); await p.click('text=+ Neuer Kunde');
  await fill('name', 'Kunde A'); await p.click('form#f button:has-text("Speichern")'); await p.waitForSelector('#nf');
  await p.click('text=+ Angebot');
  const intro = await p.inputValue('[name=intro]');
  await p.click('#addItem'); await p.locator('[data-k=desc]').fill('Test'); await p.locator('[data-k=price]').fill('10');
  await p.waitForTimeout(900);
  await p.click('#toAuftrag'); await p.waitForSelector('text=In Rechnung überführen');
  const auftragIntro = await p.inputValue('[name=intro]');
  await p.click('#toRechnung'); await p.waitForSelector('#finalize');
  const flow = await p.textContent('.flow');
  await p.click('#themeBtn');
  const theme = await p.evaluate(() => document.documentElement.dataset.theme);
  await p.screenshot({ path: 'test/shots/c2-dark.png' });
  console.log({ intro, auftragIntro: auftragIntro.slice(0, 30), flow, theme, errors });
  await b.close();
})();
